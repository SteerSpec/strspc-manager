// twoChunks leaves room for one fixture file per chunk: ~265 tokens past the
// system prompt and the overhead of 256 pay for the rules (~55), the file
// list (~55) and one ~430-byte file. It follows the system prompt's size, so
// rewording the prompt does not move the split.
func twoChunks(c *claude.Config) { c.MaxInputTokens = (len(prompt.System())+2)/3 + 256 + 265 }

// --- synthetic Messages API responses -------------------------------------

type locationJSON struct {
	File    string `json:"file"`
	Line    int    `json:"line"`
	Excerpt string `json:"excerpt"`
}

// verdictsText renders a verdict response: an object keyed by rule id.
func verdictsText(kv ...string) string {
	m := map[string]string{}
	for i := 0; i+1 < len(kv); i += 2 {
		m[kv[i]] = kv[i+1]
	}
	b, _ := json.Marshal(m)
	return string(b)
}

// detailText renders a detail response for one violated rule.
func detailText(explanation string, confidence float64, evidence ...locationJSON) string {
	if evidence == nil {
		evidence = []locationJSON{}
	}
	b, _ := json.Marshal(map[string]any{"verdict": "violated", "explanation": explanation, "confidence": confidence, "evidence": evidence})
	return string(b)
}

// withdrawnDetailText is a detail response that takes the violation back.
func withdrawnDetailText(verdict, explanation string, confidence float64) string {
	b, _ := json.Marshal(map[string]any{"verdict": verdict, "explanation": explanation, "confidence": confidence, "evidence": []locationJSON{}})
	return string(b)
}

// isDetailRequest reports whether a request body carries the detail schema
// (the only one with an evidence excerpt) rather than the verdict schema.
func isDetailRequest(body string) bool { return strings.Contains(body, `"excerpt"`) }

// message renders a Messages API response in the documented shape.
func message(stopReason, text string, extra map[string]any) string {
	content := []any{}
	if text != "" {
		content = append(content, map[string]any{"type": "text", "text": text})
	}
	m := map[string]any{
		"id":            "msg_synthetic_0001",
		"type":          "message",
		"role":          "assistant",
		"model":         testModel,
		"content":       content,
		"stop_reason":   stopReason,
		"stop_sequence": nil,
		"usage": map[string]any{
			"input_tokens":                1200,
			"output_tokens":               96,
			"cache_creation_input_tokens": 900,
			"cache_read_input_tokens":     0,
		},
	}
	for k, v := range extra {
		m[k] = v
	}
	b, _ := json.Marshal(m)
	return string(b)
}

func writeJSON(w http.ResponseWriter, status int, body string) {
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("request-id", "req_synthetic")
	w.WriteHeader(status)
	_, _ = io.WriteString(w, body)
}

func apiError(status int, typ, msg string) string {
	b, _ := json.Marshal(map[string]any{
		"type":  "error",
		"error": map[string]any{"type": typ, "message": msg},
	})
	return string(b)
}

