// Provider tests run against HTTP cassettes in testdata/cassettes/ and
// never reach the network by default (CI). The cassettes are SYNTHETIC:
// they were generated by TestSynthesizeCassettes from scripted responses
// that follow the documented Messages API shape, not recorded from the
// live API. To regenerate them after a prompt change:
//
//	STRSPC_SYNTHESIZE=1 go test ./src/ruleeval/claude/ -run TestSynthesizeCassettes
//
// Scenarios marked recordable can be re-recorded against the live API with
// STRSPC_RECORD=1 and ANTHROPIC_API_KEY set; the rest only exist in
// synthetic form.

const (
	synthComment = "SYNTHETIC cassette: generated by TestSynthesizeCassettes from scripted responses in provider_test.go, not recorded from the live Anthropic API. Regenerate with STRSPC_SYNTHESIZE=1."
	testModel    = "claude-sonnet-5-5"
)

// scenario describes one cassette-backed test case.
type scenario struct {
	name       string
	recordable bool // can be recorded against the live API (verdict-level checks only)
	single     bool // call Evaluate (per-rule) instead of EvaluateBatch
	cfg        func(*claude.Config)
	inputs     []ruleeval.RuleInput
	diff       string
	script     func(w http.ResponseWriter, body string, call int) // synthetic server behaviour
	check      func(t *testing.T, resp *ruleeval.BatchResponse, err error, p *claude.Provider, rt *replay.Transport)
}

// rule builds a fixture rule from a global-scope source. The fixture diffs
// touch src/cmd/, so a local-scope source rooted elsewhere would make the
// rule not_applicable by the prompt's own instructions.
func rule(id, body string, notes ...entity.Note) ruleeval.RuleInput {
	return ruleeval.RuleInput{
		Rule:     entity.Rule{ID: id, Revision: 1, State: "I", Body: body},
		Notes:    notes,
		EntityID: strings.SplitN(id, "-", 2)[0],
		Source:   "./rules/",
		Scope:    "global",
	}
}

