// bigHunkDiff builds a single-hunk file diff with n long added lines.
func bigHunkDiff(path string, n int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "diff --git a/%s b/%s\n--- a/%s\n+++ b/%s\n@@ -0,0 +1,%d @@\n", path, path, path, path, n)
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "+var generated%03d = %q\n", i, strings.Repeat("x", 40))
	}
	return b.String()
}

func cassettePath(name string) string {
	return filepath.Join("testdata", "cassettes", name+".json")
}

// runScenario executes sc against the transport rt and runs its checks.
func runScenario(t *testing.T, sc scenario, rt *replay.Transport, cfg claude.Config) {
	t.Helper()
	cfg.HTTPClient = &http.Client{Transport: rt}
	cfg.Model = testModel
	if sc.cfg != nil {
		sc.cfg(&cfg)
	}
	p, err := claude.New(cfg)
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	var resp *ruleeval.BatchResponse
	if sc.single {
		in := sc.inputs[0]
		var v *ruleeval.EvalResponse
		v, err = p.Evaluate(ctx, ruleeval.EvalRequest{
			Rule: in.Rule, Notes: in.Notes, Diff: sc.diff,
			EntityID: in.EntityID, Source: in.Source, Scope: in.Scope,
		})
		if v != nil {
			resp = &ruleeval.BatchResponse{Verdicts: map[string]*ruleeval.EvalResponse{in.Rule.ID: v}}
		}
	} else {
		resp, err = p.EvaluateBatch(ctx, ruleeval.BatchRequest{EntityID: "CMD", Inputs: sc.inputs, Diff: sc.diff})
	}
	sc.check(t, resp, err, p, rt)
}

// TestProvider_Scenarios replays cassettes (default) or records against the
// live API when STRSPC_RECORD=1 and ANTHROPIC_API_KEY are set.
func TestProvider_Scenarios(t *testing.T) {
	mode := replay.ModeFromEnv()
	key := os.Getenv(claude.EnvAPIKey)
	if mode == replay.ModeRecord && key == "" {
		t.Fatalf("%s=1 requires %s to be set", replay.EnvRecord, claude.EnvAPIKey)
	}
	for _, sc := range scenarios() {
		t.Run(sc.name, func(t *testing.T) {
			var upstream http.RoundTripper
			cfg := claude.Config{APIKey: "test-key"}
			path := cassettePath(sc.name)
			if mode == replay.ModeRecord {
				if !sc.recordable {
					t.Skipf("scenario %q only exists in synthetic form; regenerate with STRSPC_SYNTHESIZE=1", sc.name)
				}
				// Start from a fresh cassette: appending live responses after
				// the synthetic ones would leave replay serving the synthetic
				// answer first.
				if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
					t.Fatal(err)
				}
				upstream = http.DefaultTransport
				cfg.APIKey = key
			}
			rt, err := replay.New(path, mode, upstream)
			if err != nil {
				t.Fatal(err) // missing cassette fails CI loudly
			}
			if mode == replay.ModeRecord {
				rt.SetComment("Recorded from the live Anthropic API with STRSPC_RECORD=1 (model " + testModel + ").")
			}
			runScenario(t, sc, rt, cfg)
			if mode == replay.ModeRecord {
				if err := rt.Save(); err != nil {
					t.Fatal(err)
				}
			}
		})
	}
}

// TestSynthesizeCassettes regenerates every cassette from the scripted
// responses above by recording the real client against a local server.
// It is a no-op unless STRSPC_SYNTHESIZE=1.
func TestSynthesizeCassettes(t *testing.T) {
	if os.Getenv("STRSPC_SYNTHESIZE") != "1" {
		t.Skip("set STRSPC_SYNTHESIZE=1 to regenerate synthetic cassettes")
	}
	for _, sc := range scenarios() {
		t.Run(sc.name, func(t *testing.T) {
			var calls atomic.Int32
			srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				body, _ := io.ReadAll(r.Body)
				sc.script(w, string(body), int(calls.Add(1)))
			}))
			defer srv.Close()

			path := cassettePath(sc.name)
			_ = os.Remove(path)
			rt, err := replay.New(path, replay.ModeRecord, http.DefaultTransport)
			if err != nil {
				t.Fatal(err)
			}
			rt.SetComment(synthComment)
			runScenario(t, sc, rt, claude.Config{APIKey: "synthetic-key", BaseURL: srv.URL})
			if err := rt.Save(); err != nil {
				t.Fatal(err)
			}
		})
	}
}

